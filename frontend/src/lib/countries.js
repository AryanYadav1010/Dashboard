// Map feature -> ISO alpha-2 code (null for features without a country code).
export function getAlpha2Code(geo) {
  return numericToAlpha2[String(geo.id).padStart(3, "0")] || null;
}

// Map feature -> display name.
export function getCountryName(geo) {
  return geo.properties?.name || "Unknown";
}
